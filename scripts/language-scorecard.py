"""Render the language conformance scorecard from the suite's declarations.

Every language under tests/language-conformance/ declares in its expect.toml
the outcome Kin has today for each capability capabilities.toml lists. The
suite for each layer measures those outcomes the same way for every language
and fails when one differs from its declaration in either direction, so the
declarations are exactly what the tests hold true. This renders them into the
scorecard section of docs/language-support.md, between its markers.

  language-scorecard.py            print the section
  language-scorecard.py --write    rewrite the section in docs/language-support.md
  language-scorecard.py --check    exit 1 when that section is not the rendering
  language-scorecard.py --json     print every cell as JSON
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

BEGIN = "<!-- language-scorecard:begin -->"
END = "<!-- language-scorecard:end -->"
STATUSES = ("pass", "partial", "fail", "refused", "n/a")

# The languages the scorecard leads with, then every other language Kin parses.
PRIMARY = ("python", "typescript", "javascript", "go", "rust")
DISPLAY = {
    "python": "Python",
    "typescript": "TypeScript",
    "javascript": "JavaScript",
    "go": "Go",
    "rust": "Rust",
    "java": "Java",
    "kotlin": "Kotlin",
    "c": "C",
    "cpp": "C++",
    "csharp": "C#",
    "ruby": "Ruby",
    "php": "PHP",
    "swift": "Swift",
    "hcl": "HCL",
}
LAYER_TITLES = {"parser": "Parser layer", "route": "Agent surface"}


class ScorecardError(Exception):
    """A declaration the scorecard cannot render."""


def load(root: Path) -> tuple[list[dict], dict[str, dict]]:
    fixtures = root / "tests" / "language-conformance"
    with open(fixtures / "capabilities.toml", "rb") as handle:
        capabilities = tomllib.load(handle)["capability"]
    names = [capability["name"] for capability in capabilities]
    languages: dict[str, dict] = {}
    for expect_path in sorted(fixtures.glob("*/expect.toml")):
        with open(expect_path, "rb") as handle:
            expect = tomllib.load(handle)
        language = expect_path.parent.name
        if expect.get("language") != language:
            raise ScorecardError(f"{expect_path} names language {expect.get('language')!r}")
        if language not in DISPLAY:
            raise ScorecardError(f"{language}: add its display name to DISPLAY in {__file__}")
        declared = {key for key in expect if key not in ("language", "sources")}
        if declared != set(names):
            raise ScorecardError(
                f"{expect_path} declares {sorted(declared ^ set(names))} unlike capabilities.toml"
            )
        for name in names:
            status = expect[name].get("status")
            if status not in STATUSES:
                raise ScorecardError(f"{expect_path} [{name}] status {status!r}")
        languages[language] = expect
    missing = set(DISPLAY) - set(languages)
    if missing:
        raise ScorecardError(f"no fixture for {sorted(missing)}")
    return capabilities, languages


def ordered(languages: dict[str, dict]) -> tuple[list[str], list[str]]:
    others = [language for language in DISPLAY if language not in PRIMARY]
    return list(PRIMARY), [language for language in others if language in languages]


def table(capabilities: list[dict], languages: dict[str, dict], columns: list[str]) -> list[str]:
    header = "| Capability | " + " | ".join(DISPLAY[language] for language in columns) + " |"
    rule = "| --- |" + " --- |" * len(columns)
    rows = [header, rule]
    for capability in capabilities:
        name = capability["name"]
        cells = [languages[language][name]["status"] for language in columns]
        rows.append(f"| `{name}` | " + " | ".join(cells) + " |")
    totals = []
    for language in columns:
        statuses = [languages[language][c["name"]]["status"] for c in capabilities]
        measured = [status for status in statuses if status != "n/a"]
        totals.append(f"{measured.count('pass')} of {len(measured)}")
    rows.append("| **passing** | " + " | ".join(totals) + " |")
    return rows


def render(capabilities: list[dict], languages: dict[str, dict]) -> str:
    primary, others = ordered(languages)
    lines = [
        BEGIN,
        "<!-- Generated by scripts/language-scorecard.py from tests/language-conformance."
        " Edit the expect.toml declarations, never this section. -->",
        "",
        "Each cell is what the language conformance suite measures for one language and"
        " capability, with the same fixture project written in every language:",
        "",
        "- **pass**: every check holds.",
        "- **partial**: some checks fail; the list below names them.",
        "- **fail**: Kin attempts it and every check fails.",
        "- **refused**: Kin does not offer it for the language today, and says so.",
        "- **n/a**: the language has no such construct.",
        "",
        "A cell's test fails when what it measures differs from the declaration in either"
        " direction, so a language cannot claim a capability it lacks, and a change that"
        " makes one work flips its cell in the same commit.",
    ]
    layers = []
    for capability in capabilities:
        if capability["layer"] not in layers:
            layers.append(capability["layer"])
    for layer in layers:
        in_layer = [capability for capability in capabilities if capability["layer"] == layer]
        lines += ["", f"### {LAYER_TITLES.get(layer, layer)}", ""]
        lines += table(in_layer, languages, primary)
        lines += ["", "Other languages Kin parses:", ""]
        lines += table(in_layer, languages, others)

    lacking, not_applicable = [], []
    for language in primary + others:
        for capability in capabilities:
            cell = languages[language][capability["name"]]
            status = cell["status"]
            label = f"**{DISPLAY[language]}, `{capability['name']}`**"
            if status in ("partial", "fail"):
                gaps = ", ".join(f"`{gap}`" for gap in cell.get("gaps", []))
                note = f" {cell['note'].strip()}" if cell.get("note") else ""
                lacking.append(f"- {label} ({status}): fails {gaps}.{note}")
            elif status == "refused":
                lacking.append(f"- {label} (refused): {cell['reason'].strip()}")
            elif status == "n/a":
                not_applicable.append(f"- {label}: {cell['reason'].strip()}")
    lines += ["", "### Cells short of pass", ""]
    lines += lacking or ["Every cell passes."]
    if not_applicable:
        lines += ["", "### Not applicable", ""] + not_applicable
    lines += ["", "### Capabilities", ""]
    for capability in capabilities:
        lines.append(f"- `{capability['name']}` ({capability['layer']}): {capability['summary']}")
    lines.append(END)
    return "\n".join(lines) + "\n"


def cells_json(capabilities: list[dict], languages: dict[str, dict]) -> str:
    cells = []
    primary, others = ordered(languages)
    for language in primary + others:
        for capability in capabilities:
            cell = languages[language][capability["name"]]
            cells.append(
                {
                    "language": language,
                    "capability": capability["name"],
                    "layer": capability["layer"],
                    "status": cell["status"],
                    "gaps": cell.get("gaps", []),
                    "reason": cell.get("reason"),
                }
            )
    return json.dumps({"cells": cells}, indent=2) + "\n"


def splice(document: str, section: str) -> str:
    start, end = document.find(BEGIN), document.find(END)
    if start < 0 or end < start:
        raise ScorecardError(f"the document holds no {BEGIN} ... {END} section")
    return document[:start] + section + document[end + len(END) + 1 :]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    try:
        capabilities, languages = load(args.root)
        if args.json:
            sys.stdout.write(cells_json(capabilities, languages))
            return 0
        section = render(capabilities, languages)
        doc = args.root / "docs" / "language-support.md"
        if args.write:
            doc.write_text(splice(doc.read_text(), section))
            return 0
        if args.check:
            current = doc.read_text()
            if splice(current, section) != current:
                print(
                    "docs/language-support.md's scorecard is not what tests/language-conformance"
                    " declares. Run scripts/language-scorecard.py --write and commit the result.",
                    file=sys.stderr,
                )
                return 1
            return 0
        sys.stdout.write(section)
        return 0
    except ScorecardError as error:
        print(f"language-scorecard: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
